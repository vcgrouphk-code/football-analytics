export function displayTeamName(name: string) {
  if (TEAM_NAMES[name]) return TEAM_NAMES[name];
  const stripped = name.replace(/\s+FC$/i, "").replace(/\s+AFC$/i, "").trim();
  return TEAM_NAMES[stripped] ?? name;
}

export function displayLeagueName(name: string) {
  return LEAGUE_NAMES[name] ?? name;
}

/** API-Football 的 2024 代表 2024/25 賽季。 */
export function displaySeason(season: string) {
  const year = Number(season);
  if (!Number.isInteger(year) || year < 1900) return season;
  return `${year}/${String(year + 1).slice(-2)}`;
}

export function displayRound(round: string | null) {
  if (!round) return round;
  const match = round.match(/^Regular Season - (\d+)$/);
  if (match) return `第 ${match[1]} 輪`;
  return round;
}
